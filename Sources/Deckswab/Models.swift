import Foundation

func fmt(_ bytes: Int64) -> String {
    ByteCountFormatter.string(fromByteCount: bytes, countStyle: .file)
}

enum CategoryGroup: String, CaseIterable, Identifiable {
    case junk = "System junk"
    case developer = "Developer"
    case files = "Your files"

    var id: String { rawValue }
    var categories: [Category] { Category.allCases.filter { self == $0.group } }
}

/// A kind of data Deckswab can find and remove. Order matters: when a file matches
/// several categories, it is listed under the first one only.
enum Category: String, CaseIterable, Identifiable, Sendable {
    case appCaches, logs, appUpdates, iosUpdates, leftovers, trash
    case devCaches, xcode, docker, homebrew, projects, binlogs
    case installers, oldDownloads, largeFiles, iosBackups

    var id: String { rawValue }

    var group: CategoryGroup {
        switch self {
        case .appCaches, .logs, .appUpdates, .iosUpdates, .leftovers, .trash: .junk
        case .devCaches, .xcode, .docker, .homebrew, .projects, .binlogs: .developer
        case .installers, .oldDownloads, .largeFiles, .iosBackups: .files
        }
    }

    /// Your own files, and anything Deckswab can't be sure is junk, go to the Trash so they
    /// can be recovered. Everything else is regenerated by whatever made it, so it is deleted outright.
    var movesToTrash: Bool { .files == group || .leftovers == self }

    /// Safe for automatic cleaning: regenerable data that never needs a person to look at it first.
    var isAutomatic: Bool {
        switch self {
        case .appCaches, .logs, .appUpdates, .devCaches, .xcode, .binlogs: true
        default: false
        }
    }

    var title: String {
        switch self {
        case .appCaches: "App caches"
        case .logs: "Logs"
        case .appUpdates: "Leftover app updates"
        case .iosUpdates: "iOS firmware files"
        case .leftovers: "Uninstalled app leftovers"
        case .trash: "Trash"
        case .devCaches: "Package caches"
        case .xcode: "Xcode"
        case .docker: "Docker"
        case .homebrew: "Homebrew old versions"
        case .projects: "Old project dependencies"
        case .binlogs: "Local site binlogs"
        case .installers: "Installers"
        case .oldDownloads: "Old downloads"
        case .largeFiles: "Large files"
        case .iosBackups: "iPhone & iPad backups"
        }
    }

    var symbol: String {
        switch self {
        case .appCaches: "shippingbox.fill"
        case .logs: "doc.text.fill"
        case .appUpdates: "arrow.down.app.fill"
        case .iosUpdates: "iphone.gen3.circle.fill"
        case .leftovers: "puzzlepiece.extension.fill"
        case .trash: "trash.fill"
        case .devCaches: "cube.box.fill"
        case .xcode: "hammer.fill"
        case .docker: "server.rack"
        case .homebrew: "mug.fill"
        case .projects: "folder.fill.badge.gearshape"
        case .binlogs: "cylinder.split.1x2.fill"
        case .installers: "opticaldiscdrive.fill"
        case .oldDownloads: "arrow.down.circle.fill"
        case .largeFiles: "scalemass.fill"
        case .iosBackups: "iphone"
        }
    }

    var summary: String {
        switch self {
        case .appCaches: "Temporary data apps rebuild on their own. Caches of apps that are running are left unticked."
        case .logs: "Diagnostic logs written by apps."
        case .appUpdates: "Installers that app updaters leave behind after an update."
        case .iosUpdates: "Software updates Finder downloaded for iPhones and iPads. They're downloaded again if needed."
        case .leftovers: "Settings and support files of apps that are no longer installed. Nothing is ticked, and everything goes to the Trash."
        case .trash: "Files you already deleted. Emptying the Trash frees their space for good."
        case .devCaches: "Downloads kept by npm, pnpm, Homebrew, pip, Gradle and other package managers. They're fetched again when needed."
        case .xcode: "Build products, device support files, previews and simulator caches that Xcode regenerates. Archives are left unticked."
        case .docker: "Build cache, unused images and stopped containers. Volumes are never touched."
        case .homebrew: "Outdated versions of formulae and casks that brew cleanup would remove."
        case .projects: "node_modules, Python virtualenvs, Rust target folders and framework build caches of projects you haven't touched lately. Reinstall to bring them back."
        case .binlogs: "MySQL change logs of Local sites. Sites don't need them to run."
        case .installers: "Disk images and packages in Downloads and on the Desktop."
        case .oldDownloads: "Things you added to Downloads a while ago."
        case .largeFiles: "The biggest files in your home folder."
        case .iosBackups: "Device backups made by Finder."
        }
    }
}

struct Item: Identifiable, Sendable {
    enum Kind: Sendable {
        case file
        case binlogs
        /// Cleaned by running a tool, such as `docker builder prune`.
        case command(String, [String])
    }

    let url: URL
    let title: String
    let detail: String
    let size: Int64
    var preselected = true
    var kind = Kind.file
    var date: Date?
    /// Further files removed along with `url`, such as all the leftovers of one app.
    var extra: [URL] = []

    var id: String { url.path }

    var isOnDisk: Bool {
        if case .command = kind { return false }
        return true
    }
}

struct Finding: Sendable {
    let category: Category
    var items: [Item]
    var note: String?

    var size: Int64 { items.reduce(0) { $0 + $1.size } }
}

struct ScanSettings: Sendable {
    var nodeRoots: [URL]
    var keepPatterns: [String]
    var nodeMinAgeDays: Int
    var largeFileBytes: Int64
    var downloadsAgeDays: Int
    var runningApps: Set<String>
}

enum ItemSort: String, CaseIterable, Identifiable {
    case size = "Size"
    case name = "Name"
    case date = "Date"

    var id: String { rawValue }
}

/// A file moved to the Trash, so the move can be undone.
struct Trashed: Sendable {
    let original: URL
    let trashed: URL
}
